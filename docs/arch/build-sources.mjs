import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import "./architecture.js";

// A checked-in snapshot makes source reading work when index.html is opened
// directly from disk. HTTP previews read the working tree instead.
const root = new URL("../../", import.meta.url);
const files = [...new Set(globalThis.LOOI_ARCH.nodes.flatMap((node) => node.files.map((file) => file.path)))];
const sources = Object.fromEntries(await Promise.all(files.map(async (path) => [path, await readFile(new URL(path, root), "utf8")])));
for (const node of globalThis.LOOI_ARCH.nodes) {
  for (const file of node.files) {
    for (const anchor of file.anchors ?? [{ label: "入口", match: file.entry }]) {
      if (!sources[file.path].includes(anchor.match)) {
        throw new Error(`${node.id}: ${file.path} 缺少源码入口 ${anchor.match}`);
      }
    }
  }
}
const payload = { generatedAt: new Date().toISOString(), sources };
const output = new URL("./sources.js", import.meta.url);
await writeFile(output, `// Generated by pnpm node docs/arch/build-sources.mjs\n// Local source snapshots; edit the original files, then regenerate.\nglobalThis.LOOI_SOURCES = ${JSON.stringify(payload)};\n`);
console.log(`已更新 ${files.length} 个源码文件 → ${fileURLToPath(output)}`);
