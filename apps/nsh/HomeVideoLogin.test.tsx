import { expect, open, test } from "nsh/test";

test("video login waits for native responses and renders real challenges and discovery", async () => {
  const app = await open("./HomeVideoLoginProbe.tsx");
  await app.press("home-miot-connect-video-btn");
  await app.type("video-login-account-input", "test-account");
  await app.type("video-login-password-input", "test-password");
  await app.press("video-login-submit-credentials");
  expect(app.texts()).toContain("test-account:13:cn");
  expect(app.texts()).toContain("正在连接小米账号");
  await app.press("complete-video-request");
  await app.waitFor("video-login-error");
  expect(app.texts()).toContain("无法连接小米账号服务，请重试当前步骤。");
  await app.press("video-login-submit-credentials");
  expect(app.texts()).toContain("test-account:13:cn");
  await app.press("complete-video-request");
  await app.waitFor("video-login-captcha-image");
  await app.press("video-login-refresh-captcha");
  expect(app.texts()).toContain("refresh-captcha");
  await app.press("complete-video-request");
  await app.type("video-login-captcha-input", "server-answer");
  await app.press("video-login-submit-captcha");
  expect(app.texts()).toContain("answer:server-answer");
  await app.press("complete-video-request");
  await app.waitFor("video-login-2fa-input");
  expect(app.texts()).toContain("验证码已发送至 a***@example.com。");
  await app.type("video-login-2fa-input", "123456");
  await app.press("video-login-submit-2fa");
  await app.press("complete-video-request");
  await app.waitFor("video-login-error");
  expect(app.texts()).toContain("验证码不正确，请重新输入。");
  expect(app.texts()).not.toContain("视频已授权");
  await app.press("video-login-submit-2fa");
  await app.press("complete-video-request");
  await app.waitFor("home-miot-view-cameras-btn");
  expect(app.texts()).toContain("已关联 2 台摄像头。");
});
